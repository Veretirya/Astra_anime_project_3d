import { chromium, devices } from '@playwright/test'
import { createServer } from 'node:http'
import { pathToFileURL } from 'node:url'
import path from 'node:path'
import fs from 'node:fs/promises'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'

const version = (await fs.readFile('src/release.ts','utf8')).match(/BUILD = '([^']+)'/)[1]
const name = `MIKA-DUO-${version}.html`
const html = await fs.readFile('dist/index.html'), offline = path.resolve('public/downloads/' + name)
const expected = JSON.parse(await fs.readFile('src/assets/mika-model.json', 'utf8')).sha256
assert.deepEqual(await fs.readFile(offline), html)
const route = '/only-this-document/theatre.html', requests = [], exceptions = []
const server = createServer((req, res) => {
  requests.push(req.url)
  if (req.url === route) res.writeHead(200, { 'Content-Type': 'text/html;charset=utf-8' }).end(html)
  else res.writeHead(404).end('Not found')
})
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
