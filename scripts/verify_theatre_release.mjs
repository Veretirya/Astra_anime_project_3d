  await p.getByRole('button', { name: 'Выбрать: Бинт', exact: true }).tap(); await p.locator('.apply-action').tap()
  assert.ok(await p.getByRole('heading', { name: 'Операция завершена' }).isVisible())
  await p.getByRole('button', { name: 'Закрыть окно' }).tap()
  await p.getByRole('button', { name: 'Вкладка Песочница', exact: true }).tap()
  const sandboxStory = p.getByRole('switch', { name: 'Катсцены в песочнице', exact: true })
  await sandboxStory.tap(); assert.equal(await sandboxStory.getAttribute('aria-checked'), 'false')
  assert.equal(await p.evaluate(() => JSON.parse(localStorage.getItem('theatre.preferences.v1')).story), true)
  await p.getByRole('button', { name: 'Невесомость', exact: true }).tap()
  assert.equal(await p.getByRole('button', { name: 'Выбрать: Рука', exact: true }).getAttribute('aria-pressed'), 'true')
  assert.equal(await p.getByRole('slider', { name: 'Сила гравитации' }).inputValue(), '0')
  await p.getByRole('button', { name: 'Вернуть покрывало', exact: true }).tap()
  assert.ok(await p.getByRole('button', { name: 'Снять покрывало', exact: true }).isVisible())
  await p.getByRole('button', { name: 'Открыть Kinema Lab', exact: true }).tap()
  await p.locator('.three-host.loaded').waitFor({ timeout: 60000 })
  assert.equal(await p.locator('.version').innerText(), `v${version}`)
  await p.getByRole('switch', { name: 'Фиксация на месте', exact: true }).tap()
  await p.getByRole('button', { name: 'Вернуться в THEATRE', exact: true }).tap()
  await p.waitForFunction(() => document.querySelector('.mobile-start')?.disabled === false)
  await p.getByRole('button', { name: 'Персонаж и импорт модели', exact: true }).tap()
  await p.getByRole('button', { name: /Своя модель/ }).tap()
  await p.locator('input[type=file]').setInputFiles({ name: 'OfflineAvatar.glb', mimeType: 'model/gltf-binary', buffer: await fs.readFile('public/models/mika.glb') })
  await p.locator('.avatar-verified').waitFor(); await p.getByRole('button', { name: 'Применить модель',exact:true }).tap({timeout:60000})
  await p.locator('.webgl-host.show').waitFor(); await p.waitForFunction(() => document.querySelector('.mobile-start')?.disabled === false)
  assert.match(await p.locator('.patient-row').innerText(), /OfflineAvatar/)
  assert.equal(requests.filter(r => r !== route).length, 0)
  console.log('PASS Mobile production game, all assets unavailable, full touch-only operation, no missing GLB')
  await c.close()
  const local = await browser.newContext({ offline: true, viewport: { width: 1200, height: 820 } }), q = await local.newPage()
  let network = 0; q.on('request', r => { if (/^https?:/.test(r.url())) network++ }); q.on('pageerror', e => exceptions.push(e.message))
