  const download = await event; assert.equal(download.suggestedFilename(), name)
  const savedPath = path.resolve('artifacts/downloaded-theatre.html'); await download.saveAs(savedPath)
  await q.goto(pathToFileURL(savedPath).href, { waitUntil: 'load' })
  await q.waitForFunction(() => document.querySelector('.start-button')?.disabled === false)
  assert.equal(await q.locator('.scene-error').count(), 0)
  await q.getByRole('button', { name: 'Открыть Kinema Lab', exact: true }).click(); await q.locator('.three-host.loaded').waitFor({ timeout: 60000 })
